/** The 109 command names. */
export type OpName = (typeof LAYOUTS)[number][0];

if (LAYOUTS.length !== COMMAND_COUNT) throw new Error(`the AI command table has ${LAYOUTS.length} entries, not ${COMMAND_COUNT}`);

/** Every command, indexed by its opcode number. */
export const OPCODES: readonly OpcodeInfo[] = Object.freeze(LAYOUTS.map(([name, ...args], code) => ({ code, name, args: [...args] })));

/** Opcode numbers by command name, such as `OP.IfRandomLessThan`. */
export const OP = Object.freeze(Object.fromEntries(OPCODES.map(({ name, code }) => [name, code]))) as Readonly<Record<OpName, number>>;
