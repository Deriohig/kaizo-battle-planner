// The item records the trainer AI reads: pl_item_data.narc, the ItemData struct (include/item.h:56), indexed by item ID
// through the arm9 table sItemArchiveIDs (src/item.c:57), the way BattleSystem_GetItemData reads them (battle_lib.c:7254).

import { RomError } from '../../errors.js';
import { readNarc } from '../../nds/narc.js';
import { blzDecompress } from '../../nds/overlay.js';

/** What `Item_Get` (item.c:153) returns for each parameter the AI reads. Booleans are the C's non-zero tests. */
export interface AiItemRecord {
  id: number; holdEffect: number; holdParam: number; flingPower: number; naturalGiftPower: number; naturalGiftType: number;
  hpRestore: boolean; hpRestored: number; healSleep: boolean; healPoison: boolean; healBurn: boolean; healFreeze: boolean;
  healParalysis: boolean; healConfusion: boolean; atkStages: number; defStages: number; spAtkStages: number;
  spDefStages: number; speedStages: number; accStages: number; guardSpec: boolean;
}

const ITEM_DATA_NARC = 'itemtool/itemdata/pl_item_data.narc';
const ITEM_NONE = 0;
/** NUM_ITEMS = MAX_ITEMS - 1 (constants/items.h:84), MAX_ITEMS being 468 (generated/items.txt:469). */
const NUM_ITEMS = 467;

/** sizeof(ItemData) in the game, with ALIGN_4 (include/item.h:77). The NARC's members are 34 bytes, padded to 36. */
const ITEM_DATA_SIZE = 36;
/** The bytes up to the last field the record reads, hpRestored (0x1B). */
const ITEM_DATA_READ_SIZE = 0x1c;
// ItemData offsets (include/item.h:56–77).
const HOLD_EFFECT = 0x02;
const EFFECT_PARAM = 0x03;
const FLING_POWER = 0x06;
const NATURAL_GIFT_POWER = 0x07;
/** A u16: naturalGiftType in bits 0–4, then preventToss, canRegister, fieldPocket and battlePocket. */
const NATURAL_GIFT_TYPE = 0x08;
const NATURAL_GIFT_TYPE_MASK = 0x1f;
const PARTY_USE = 0x0c;
/** The union of `u8 dummy` and ItemPartyParam (include/item.h:8–54), whose bitfields fill each byte from bit 0. */
const PARTY_PARAMS = 0x0e;

/** ItemArchiveIDs: u16 dataID, iconID, paletteID, gen3ID (tools/dataproc/data/item_id_map.h.template). */
const ARCHIVE_IDS_SIZE = 8;
/**
 * Vanilla sItemArchiveIDs[0..15], ITEM_NONE to ITEM_QUICK_BALL, generated by itemproc (tools/dataproc/src/itemproc.c:337–353):
 * dataID counts the items with data; iconID and paletteID are the icons' 0-based lines in res/items/item_icon.order
 * (the Timer Ball shares the Repeat Ball's palette, the Premier Ball the Luxury Ball's); gen3ID is the GBA item
 * (constants/gba/items.h), none for the Dusk, Heal and Quick Balls.
 */
const VANILLA_ARCHIVE_IDS_HEAD = [
  [0, 707, 708, 0], [1, 2, 3, 1], [2, 4, 5, 2], [3, 6, 7, 3], [4, 8, 9, 4], [5, 10, 11, 5], [6, 12, 13, 6], [7, 14, 15, 7],
  [8, 16, 17, 8], [9, 18, 19, 9], [10, 20, 19, 10], [11, 21, 22, 11], [12, 23, 22, 12], [13, 663, 664, 0], [14, 665, 666, 0],
  [15, 667, 668, 0],
];

// The NDS header's arm9 fields, and the arm9 module params (the SDK's _start_ModuleParams).
const ARM9_ROM_OFFSET = 0x20;
const ARM9_RAM_ADDRESS = 0x28;
const ARM9_SIZE = 0x2c;
/** The module params end with the nitrocode magic, u32 0xDEC00621 then u32 0x2106C0DE, at +0x1C. */
const NITROCODE = [0x21, 0x06, 0xc0, 0xde, 0xde, 0xc0, 0x06, 0x21];
const NITROCODE_IN_PARAMS = 0x1c;
/** The RAM address where the BLZ-compressed part ends, or 0 when the arm9 is not compressed. */
const COMPRESSED_STATIC_END = 0x14;

/** Every offset in `haystack` where `needle` starts. */
export function findBytes(haystack: Uint8Array, needle: readonly number[]): number[] {
  const hits: number[] = [];
  outer: for (let at = 0; at + needle.length <= haystack.length; at++) {
    for (let i = 0; i < needle.length; i++) if (haystack[at + i] !== needle[i]) continue outer;
    hits.push(at);
  }
  return hits;
}

/**
 * The ROM's arm9 binary, BLZ-decompressed when its module params give a compressed static end; the bytes past that
 * end are stored plain and follow. The params are found by their magic, which sits in the plain start of the binary.
 * The BLZ footer alone cannot say: an uncompressed arm9's last eight bytes are code, and the hack's look like a footer.
 */
export function readArm9(rom: Uint8Array): Uint8Array {
  const header = new DataView(rom.buffer, rom.byteOffset, rom.byteLength);
  const start = header.getUint32(ARM9_ROM_OFFSET, true);
  const arm9 = rom.subarray(start, start + header.getUint32(ARM9_SIZE, true));
  const magic = findBytes(arm9, NITROCODE);
  if (magic.length !== 1 || magic[0]! < NITROCODE_IN_PARAMS) {
    throw new RomError('BAD_FORMAT', `expected one arm9 module params block, found ${magic.length} nitrocode magics`);
  }
  const params = magic[0]! - NITROCODE_IN_PARAMS;
  const view = new DataView(arm9.buffer, arm9.byteOffset, arm9.byteLength);
  const compressedEnd = view.getUint32(params + COMPRESSED_STATIC_END, true);
  if (compressedEnd === 0) return arm9;

  const length = compressedEnd - header.getUint32(ARM9_RAM_ADDRESS, true);
  if (length <= params || length > arm9.length) {
    throw new RomError('BAD_FORMAT', `the arm9's compressed static end 0x${compressedEnd.toString(16)} is outside its ${arm9.length} bytes`);
  }
  const code = blzDecompress(arm9.subarray(0, length));
  const out = new Uint8Array(code.length + arm9.length - length);
  out.set(code);
  out.set(arm9.subarray(length), code.length);
  return out;
}

/**
 * The item-data index of each item ID 0..NUM_ITEMS: the first u16 (dataID) of its sItemArchiveIDs entry. The table is
 * found in `arm9` (decompressed) by vanilla's first 16 entries; RomError('BAD_FORMAT') unless they occur exactly once.
 */
export function itemDataIndices(arm9: Uint8Array): number[] {
  const head = new DataView(new ArrayBuffer(VANILLA_ARCHIVE_IDS_HEAD.length * ARCHIVE_IDS_SIZE));
  VANILLA_ARCHIVE_IDS_HEAD.forEach((ids, entry) => ids.forEach((id, i) => head.setUint16(entry * ARCHIVE_IDS_SIZE + i * 2, id, true)));
  const hits = findBytes(arm9, [...new Uint8Array(head.buffer)]);
  if (hits.length !== 1) {
    const where = hits.map((offset) => `0x${offset.toString(16)}`).join(', ');
    throw new RomError('BAD_FORMAT', `expected one item ID table (sItemArchiveIDs) in arm9, found ${hits.length}${where ? ` (at ${where})` : ''}`);
  }
  const start = hits[0]!;
  if (start + (NUM_ITEMS + 1) * ARCHIVE_IDS_SIZE > arm9.length) {
    throw new RomError('BAD_FORMAT', `the item ID table at 0x${start.toString(16)} runs past the end of arm9`);
  }
  const view = new DataView(arm9.buffer, arm9.byteOffset, arm9.byteLength);
  return Array.from({ length: NUM_ITEMS + 1 }, (_, item) => view.getUint16(start + item * ARCHIVE_IDS_SIZE, true));
}

/** One ItemData record, as `Item_Get` (item.c:153–198) reads each parameter. `record` holds at least 0x1C bytes. */
export function decodeItemRecord(id: number, record: Uint8Array): AiItemRecord {
  if (record.length < ITEM_DATA_READ_SIZE) {
    throw new RomError('BAD_FORMAT', `item ${id}'s data record is ${record.length} bytes; it needs ${ITEM_DATA_READ_SIZE}`);
  }
  const view = new DataView(record.buffer, record.byteOffset, record.byteLength);
  const partyUse = record[PARTY_USE]!;
  // item.c:186–194: with partyUse FALSE every party parameter is `dummy`, the union's first byte (itemproc.c keeps a
  // ball, rod or mail index there), with TRUE it is the ItemPartyParam field, and any other partyUse gives 0.
  const param = (byte: number, shift: number, bits: number): number => {
    if (partyUse === 0) return record[PARTY_PARAMS]!;
    if (partyUse !== 1) return 0;
    return (record[PARTY_PARAMS + byte]! >> shift) & ((1 << bits) - 1);
  };
  const flag = (byte: number, bit: number): boolean => param(byte, bit, 1) !== 0;
  return {
    id,
    holdEffect: record[HOLD_EFFECT]!,
    holdParam: record[EFFECT_PARAM]!,
    flingPower: record[FLING_POWER]!,
    naturalGiftPower: record[NATURAL_GIFT_POWER]!,
    naturalGiftType: view.getUint16(NATURAL_GIFT_TYPE, true) & NATURAL_GIFT_TYPE_MASK,
    hpRestore: flag(5, 2),
    // A u8 field, so the AI's `u8 hpRestore` (trainer_ai.c:4061, set at 4106) holds it unchanged.
    hpRestored: param(13, 0, 8),
    healSleep: flag(0, 0),
    healPoison: flag(0, 1),
    healBurn: flag(0, 2),
    healFreeze: flag(0, 3),
    healParalysis: flag(0, 4),
    healConfusion: flag(0, 5),
    atkStages: param(1, 4, 4),
    defStages: param(2, 0, 4),
    spAtkStages: param(2, 4, 4),
    spDefStages: param(3, 0, 4),
    speedStages: param(3, 4, 4),
    accStages: param(4, 0, 4),
    guardSpec: flag(0, 7),
  };
}

/**
 * Every item's record, indexed by item ID 0..NUM_ITEMS. `arm9` is decompressed (`readArm9`). An item whose record lies
 * past the battle's item table is null: the cartridge reads whatever memory follows the table.
 */
export function decodeItems(files: Map<string, Uint8Array>, arm9: Uint8Array): (AiItemRecord | null)[] {
  const narc = files.get(ITEM_DATA_NARC);
  if (narc === undefined) throw new RomError('MISSING_FILE', `The ROM has no ${ITEM_DATA_NARC}`);
  const dataIds = itemDataIndices(arm9);
  // ItemTable_Load (item.c:394–398, battle_controller_player.c:189) reads Item_FileID(NUM_ITEMS) records in one go
  // from the start of member 0, and ItemTable_Index (item.c:400–403) steps through them by sizeof(ItemData). So the
  // table holds data indices 0 to Item_FileID(NUM_ITEMS) - 1, which leaves out NUM_ITEMS's own record.
  const tableCount = dataIds[NUM_ITEMS]!;
  const first = readNarc(narc)[0];
  if (first === undefined) throw new RomError('BAD_FORMAT', `${ITEM_DATA_NARC} is empty`);
  const start = first.byteOffset - narc.byteOffset;
  const table = narc.subarray(start, start + tableCount * ITEM_DATA_SIZE);
  if (table.length < tableCount * ITEM_DATA_SIZE) {
    throw new RomError('BAD_FORMAT', `${ITEM_DATA_NARC} holds ${table.length} bytes of records; the battle reads ${tableCount * ITEM_DATA_SIZE}`);
  }
  return dataIds.map((dataId, item) => {
    // Item_FileID (item.c:53) gives ITEM_NONE data index 0 without reading sItemArchiveIDs.
    const index = item === ITEM_NONE ? 0 : dataId;
    if (index >= tableCount) return null;
    return decodeItemRecord(item, table.subarray(index * ITEM_DATA_SIZE, (index + 1) * ITEM_DATA_SIZE));
  });
}
